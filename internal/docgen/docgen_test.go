package docgen_test

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/TeachMeHIPAA/teachmehipaa-cli/internal/docgen"
)

func TestTheCommittedCommandReferenceIsCurrent(t *testing.T) {
	files, err := docgen.Commands()
	if err != nil {
		t.Fatal(err)
	}
	stale, err := docgen.Stale(filepath.Join("../..", docgen.Dir), files)
	if err != nil {
		t.Fatal(err)
	}
	if len(stale) > 0 {
		t.Errorf("stale command reference pages %v; run make docs", stale)
	}
}

func TestTheReferenceHasAPagePerCommandWithoutDates(t *testing.T) {
	files, err := docgen.Commands()
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"tmh.md", "tmh_learners.md", "tmh_learners_list.md", "tmh_events_tail.md",
		"tmh_login.md", "tmh_get.md", "tmh_completion_bash.md"} {
		if _, ok := files[name]; !ok {
			t.Errorf("no page %s", name)
		}
	}
	if _, ok := files["tmh_help.md"]; ok {
		t.Error("the help command has a page")
	}
	for name, page := range files {
		if strings.Contains(string(page), "Auto generated by spf13/cobra") {
			t.Errorf("%s carries cobra's dated footer, which changes every run", name)
		}
	}
}

func TestStaleFindsChangedMissingAndRemovedPages(t *testing.T) {
	dir := t.TempDir()
	files := map[string][]byte{"tmh.md": []byte("root\n"), "tmh_a.md": []byte("a\n"), "tmh_b.md": []byte("b\n")}
	if err := docgen.Write(dir, files); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "tmh_a.md"), []byte("edited\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "tmh_gone.md"), []byte("old\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(dir, "tmh_b.md")); err != nil {
		t.Fatal(err)
	}

	stale, err := docgen.Stale(dir, files)

	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"tmh_a.md", "tmh_b.md", "tmh_gone.md"}; !slices.Equal(stale, want) {
		t.Errorf("Stale = %v, want %v", stale, want)
	}
	if err := docgen.Write(dir, files); err != nil {
		t.Fatal(err)
	}
	if stale, _ := docgen.Stale(dir, files); len(stale) != 0 {
		t.Errorf("after Write, Stale = %v", stale)
	}
}
