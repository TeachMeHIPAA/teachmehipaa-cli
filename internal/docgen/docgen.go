// Package docgen writes the Markdown command reference in
// docs/reference/commands from tmh's real command tree with cobra/doc, so the
// reference shows exactly the commands, flags and help text tmh has.
package docgen

import (
	"bytes"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"

	"github.com/TeachMeHIPAA/teachmehipaa-cli/internal/cmdutil"
	"github.com/TeachMeHIPAA/teachmehipaa-cli/internal/commands"
	"github.com/TeachMeHIPAA/teachmehipaa-cli/internal/version"
)

// Dir is where the command reference lives, relative to the repository root.
const Dir = "docs/reference/commands"

const banner = "<!-- Code generated by cmd/docgen from tmh's command tree. DO NOT EDIT. -->\n\n"

// Commands returns one page per command, keyed by file name, as
// cobra/doc's GenMarkdownTree names them (tmh_learners_list.md).
func Commands() (map[string][]byte, error) {
	root := commands.NewRoot(cmdutil.Deps{
		Stdin:  strings.NewReader(""),
		Stdout: io.Discard,
		Stderr: io.Discard,
		// The version flag's help would otherwise depend on the build.
		Build: version.Info{Version: "dev"},
	})
	files := map[string][]byte{}
	var walk func(cmd *cobra.Command) error
	walk = func(cmd *cobra.Command) error {
		if cmd != root && (!cmd.IsAvailableCommand() || cmd.IsAdditionalHelpTopicCommand()) {
			return nil
		}
		// The tag dates each page, which would make every run a change.
		cmd.DisableAutoGenTag = true
		for _, child := range cmd.Commands() {
			if err := walk(child); err != nil {
				return err
			}
		}
		var page bytes.Buffer
		page.WriteString(banner)
		if err := doc.GenMarkdown(cmd, &page); err != nil {
			return err
		}
		files[strings.ReplaceAll(cmd.CommandPath(), " ", "_")+".md"] = page.Bytes()
		return nil
	}
	if err := walk(root); err != nil {
		return nil, err
	}
	return files, nil
}

// Stale lists the pages in dir that differ from files, including pages for
// commands tmh no longer has.
func Stale(dir string, files map[string][]byte) ([]string, error) {
	stale := []string{}
	for name, want := range files {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil && !os.IsNotExist(err) {
			return nil, err
		}
		if !bytes.Equal(got, want) {
			stale = append(stale, name)
		}
	}
	leftovers, err := leftovers(dir, files)
	if err != nil {
		return nil, err
	}
	stale = append(stale, leftovers...)
	slices.Sort(stale)
	return stale, nil
}

// Write replaces the pages in dir and deletes the ones for removed commands.
func Write(dir string, files map[string][]byte) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	leftovers, err := leftovers(dir, files)
	if err != nil {
		return err
	}
	for _, name := range leftovers {
		if err := os.Remove(filepath.Join(dir, name)); err != nil {
			return err
		}
	}
	for name, contents := range files {
		if err := os.WriteFile(filepath.Join(dir, name), contents, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// leftovers are generated pages in dir that files no longer has; the
// directory holds nothing hand-written.
func leftovers(dir string, files map[string][]byte) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	names := []string{}
	for _, entry := range entries {
		if _, current := files[entry.Name()]; !current && strings.HasSuffix(entry.Name(), ".md") {
			names = append(names, entry.Name())
		}
	}
	return names, nil
}
