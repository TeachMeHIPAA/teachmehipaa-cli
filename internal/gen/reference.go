// ReferencePath is where the resource reference lives, relative to the
// repository root.
const ReferencePath = "docs/reference/resources.md"

const referenceBanner = "<!-- Code generated by cmd/gen from openapi/sdk-ir.json. DO NOT EDIT. -->"

type irScope struct {
	Name        string `json:"name"`
	Description string `json:"description"`
}

type irServer struct {
	Environment string `json:"environment"`
	URL         string `json:"url"`
}

// Reference renders docs/reference/resources.md: every IR method as the
// `tmh` command that calls it, with its route, Scopes, retry, idempotency
// and conditional behavior, and what it prints. It uses the same method
// builder as the commands, so the two cannot disagree.
func Reference(raw []byte) ([]byte, error) {
	ir, err := decodeIR(raw)
	if err != nil {
		return nil, err
	}
	g := &generator{types: map[string]irType{}}
	for _, t := range ir.Types {
		g.types[t.Name] = t
	}
	var auth struct {
		Scopes []irScope `json:"scopes"`
	}
	if err := json.Unmarshal(ir.Auth, &auth); err != nil {
		return nil, fmt.Errorf("auth: %w", err)
	}
	var servers []irServer
	if err := json.Unmarshal(ir.Servers, &servers); err != nil {
		return nil, fmt.Errorf("servers: %w", err)
	}
	baseURL := map[string]string{}
	for _, s := range servers {
		baseURL[s.Environment] = s.URL
	}

	resources := slices.Clone(ir.Resources)
	slices.SortFunc(resources, func(a, b irResource) int {
		return strings.Compare(commandPath(a.Path), commandPath(b.Path))
	})
	methods := 0
	for _, r := range resources {
		methods += len(r.Methods)
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "%s\n\n# Resource reference\n\n", referenceBanner)
	out.WriteString("```text\ntmh <resource> <method> [<id>...] [flags]\n```\n\n")
	fmt.Fprintf(&out, "One section per Developer API operation: %d commands over %d resources, generated "+
		"from API release `%s`. Under each command, a table gives the HTTP route, the Scopes it needs, what "+
		"it prints and whether `tmh` retries it, followed by an example. The "+
		"[command reference](commands/tmh.md) has every flag with its default, and "+
		"[Requests](../topics/requests.md) shows how arguments, flags and `-d` turn into a request.\n\n",
		methods, len(resources), ir.Source.Release)
	fmt.Fprintf(&out, "Routes are relative to the Environment's base URL: `%s` for Live, `%s` for Sandbox. "+
		"`{orgId}` never appears on the command line; `tmh` reads it from your credentials. "+
		"`tmh events tail`, `tmh events resend` and the raw `tmh get`, `post`, `put`, `patch` and `delete` "+
		"belong to `tmh` itself and call no single operation, so they have no section here.\n\n",
		baseURL["live"], baseURL["sandbox"])

	// The example under a command is its code sample: the one the API
	// reference shows. Methods that share an operationId show the first's.
	owners := map[string]bool{}
	seen := map[string]bool{}
	for _, r := range ir.Resources {
		for _, m := range r.Methods {
			if !seen[m.OperationID] {
				seen[m.OperationID] = true
				owners[strings.Join(append(slices.Clone(r.Path), m.Name), ".")] = true
			}
		}
	}

	out.WriteString("## Contents\n\n")
	for _, r := range resources {
		name := commandPath(r.Path)
		links := []string{}
		for _, m := range sortedMethods(r.Methods) {
			links = append(links, fmt.Sprintf("[`%s`](#%s)", kebab(m.Name), doctest.Slug(name+" "+kebab(m.Name))))
		}
		fmt.Fprintf(&out, "- [`%s`](#%s): %s\n", name, doctest.Slug(name), strings.Join(links, ", "))
	}

	out.WriteString("\n## Scopes\n\n")
	out.WriteString("`tmh whoami` lists the Scopes your API client holds. Where a command names more than " +
		"one set, any one set is enough. A missing Scope fails the command with exit code 2; see " +
		"[Login](../topics/login.md#scopes).\n\n")
	out.WriteString("| Scope | Allows |\n|---|---|\n")
	for _, s := range auth.Scopes {
		fmt.Fprintf(&out, "| `%s` | %s |\n", s.Name, cell(s.Description))
	}

	for _, r := range resources {
		name := commandPath(r.Path)
		fmt.Fprintf(&out, "\n## `%s`\n", name)
		for _, m := range sortedMethods(r.Methods) {
			method, err := g.method(r.Path, m)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", method.Name, err)
			}
			example := ""
			if owners[method.Name] {
				if example, err = g.sample(r.Path, m); err != nil {
					return nil, fmt.Errorf("%s: %w", method.Name, err)
				}
			}
			writeReferenceMethod(&out, name, m, method, example)
		}
	}
	return out.Bytes(), nil
}

func writeReferenceMethod(out *bytes.Buffer, resourceName string, m irMethod, method resource.Method, example string) {
	command := resourceName + " " + method.Use
	verb := strings.Fields(method.Use)[0]
	fmt.Fprintf(out, "\n### `%s %s`\n\n", resourceName, verb)
	if m.Summary != nil && strings.TrimSpace(*m.Summary) != "" {
		fmt.Fprintf(out, "%s\n\n", strings.TrimSpace(*m.Summary))
	}
	if m.Description != nil && strings.TrimSpace(*m.Description) != "" {
		fmt.Fprintf(out, "%s\n\n", strings.TrimSpace(*m.Description))
	}
	fmt.Fprintf(out, "```text\n%s [flags]\n```\n\n", command)

	route := m.Path.Template
	if m.Path.CustomVerb != nil {
		route += ":" + *m.Path.CustomVerb
	}
	rows := [][2]string{
		{"HTTP", fmt.Sprintf("`%s %s`", m.HTTPMethod, route)},
		{"Scopes", referenceScopes(m.Security)},
		{"Prints", prints(m, method)},
		{"Retries", retries(method)},
		{"Idempotency", idempotency(m.IdempotencyKey)},
	}
	switch method.IfMatch {
	case resource.Required:
		rows = append(rows, [2]string{"Conditional", "`--if-match <etag>` is required"})
	case resource.Optional:
		rows = append(rows, [2]string{"Conditional", "`--if-match <etag>` makes the write conditional"})
	}
	if method.PreviewMethod != "" {
		preview := method.PreviewMethod[strings.LastIndex(method.PreviewMethod, ".")+1:]
		rows = append(rows, [2]string{"Preview", fmt.Sprintf(
			"`--preview` runs [`%s %s`](#%s) instead, which checks the input and changes nothing",
			resourceName, kebab(preview), doctest.Slug(resourceName+" "+kebab(preview)))})
	}
	out.WriteString("| | |\n|---|---|\n")
	for _, row := range rows {
		fmt.Fprintf(out, "| %s | %s |\n", row[0], row[1])
	}

	flags := slices.Clone(method.Query)
	if method.Body != nil {
		flags = append(flags, method.Body.Fields...)
	}
	if len(flags) > 0 || (method.Body != nil && len(method.Body.FileParts) > 0) {
		out.WriteString("\n| Flag | Description |\n|---|---|\n")
		if method.Body != nil {
			for _, part := range method.Body.FileParts {
				fmt.Fprintf(out, "| `--%s <path>` | The `%s` file to upload; `-` reads stdin |\n",
					part.Name, part.ContentType)
			}
		}
		for _, flag := range flags {
			fmt.Fprintf(out, "| `--%s` | %s |\n", flag.Name, cell(flag.Usage))
		}
	}
	if example != "" {
		fmt.Fprintf(out, "\nExample:\n\n```sh\n%s\n```\n", example)
	}
	page := strings.ReplaceAll(resourceName, " ", "_") + "_" + verb + ".md"
	fmt.Fprintf(out, "\nAll flags: [`%s %s`](commands/%s).\n", resourceName, verb, page)
}

func prints(m irMethod, method resource.Method) string {
	switch m.Response.Kind {
	case "model":
		return fmt.Sprintf("%s as JSON", typeName(m.Response.Type))
	case "writeResult":
		return fmt.Sprintf("%s, or %s when it was created, as JSON", typeName(m.Response.Existing), typeName(m.Response.Created))
	case "page":
		return fmt.Sprintf("A page of %s as JSON; `--all` follows every page and `--ndjson` prints one item per line",
			typeName(&m.Pagination.ItemType))
	case "operation":
		text := "An `Operation` as JSON; `--wait` waits until it is done"
		if method.Export {
			text += ", and `-o <file>` saves the finished CSV"
		}
		return text
	case "binary":
		return fmt.Sprintf("The `%s` file; `-o <file>` saves it, `-o -` writes it to stdout", m.Response.ContentType)
	case "empty":
		return "Nothing"
	}
	return m.Response.Kind
}

func retries(method resource.Method) string {
	if method.RetrySafe {
		return "Retried on connection errors, 409 `conflict`, 429 and 5xx (`--max-retries`)"
	}
	return "Never retried"
}

func idempotency(key string) string {
	switch key {
	case "required":
		return "`tmh` generates an Idempotency-Key and reuses it on retries; `--idempotency-key` sets your own"
	case "optional":
		return "`--idempotency-key` makes a replay return the first result"
	}
	return "None"
}

func referenceScopes(security irSecurity) string {
	if security.Kind == "none" {
		return "None (public): runs before `tmh login`"
	}
	alternatives := []string{}
	for _, all := range security.AnyOf {
		if len(all) == 0 {
			return "Any Access token"
		}
		names := []string{}
		for _, scope := range all {
			names = append(names, "`"+scope+"`")
		}
		alternatives = append(alternatives, strings.Join(names, " and "))
	}
	return strings.Join(alternatives, " or ")
}

func typeName(ref *irTypeRef) string {
	if ref == nil || ref.Name == "" {
		return "an object"
	}
	return "`" + ref.Name + "`"
}

func sortedMethods(methods []irMethod) []irMethod {
	sorted := slices.Clone(methods)
	slices.SortFunc(sorted, func(a, b irMethod) int { return strings.Compare(kebab(a.Name), kebab(b.Name)) })
	return sorted
}

// commandPath is how tmh spells a resource: ["webhookSubscriptions"] is
// "tmh webhook-subscriptions".
func commandPath(path []string) string {
	words := []string{"tmh"}
	for _, p := range path {
		words = append(words, kebab(p))
	}
	return strings.Join(words, " ")
}

func cell(text string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(text), " "), "|", `\|`)
}
