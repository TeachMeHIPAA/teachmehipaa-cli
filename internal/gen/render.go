package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"github.com/TeachMeHIPAA/teachmehipaa-cli/internal/resource"
)

// Banner is Go's generated-code marker (go.dev/s/generatedcode); the
// generator owns exactly the files that start with it.
const Banner = "// Code generated by cmd/gen from openapi/sdk-ir.json. DO NOT EDIT."

const (
	resourceImport = `"github.com/TeachMeHIPAA/teachmehipaa-cli/internal/resource"`
	cobraImport    = `"github.com/spf13/cobra"`
	cmdutilImport  = `"github.com/TeachMeHIPAA/teachmehipaa-cli/internal/cmdutil"`
)

// render writes one file per top-level resource, holding its methods and
// those of its nested resources, plus register_gen.go wiring the tree.
func render(roots []*group) (map[string][]byte, error) {
	files := map[string][]byte{}
	for _, root := range roots {
		var src bytes.Buffer
		writeHeader(&src, resourceImport)
		writeMethods(&src, root)
		name := snake(root.path[0]) + "_gen.go"
		if name == "register_gen.go" {
			return nil, fmt.Errorf("resource %s collides with register_gen.go", root.path[0])
		}
		formatted, err := gofmt(name, src.Bytes())
		if err != nil {
			return nil, err
		}
		files[name] = formatted
	}
	var src bytes.Buffer
	writeHeader(&src, cobraImport, "", cmdutilImport, resourceImport)
	src.WriteString("// Register adds a `tmh <resource> <method>` command for every method in\n")
	src.WriteString("// the IR to root.\n")
	src.WriteString("func Register(root *cobra.Command, f *cmdutil.Factory) {\n\troot.AddCommand(\n")
	for _, root := range roots {
		writeGroup(&src, root)
		src.WriteString(",\n")
	}
	src.WriteString("\t)\n}\n")
	formatted, err := gofmt("register_gen.go", src.Bytes())
	if err != nil {
		return nil, err
	}
	files["register_gen.go"] = formatted
	return files, nil
}

func writeHeader(src *bytes.Buffer, imports ...string) {
	fmt.Fprintf(src, "%s\n\npackage generated\n\nimport (\n", Banner)
	for _, path := range imports {
		fmt.Fprintf(src, "\t%s\n", path)
	}
	src.WriteString(")\n\n")
}

func writeGroup(src *bytes.Buffer, g *group) {
	fmt.Fprintf(src, "resource.NewGroup(f, %q, %q, %s", Kebab(g.path[len(g.path)-1]),
		humanize(g.path[len(g.path)-1]), variable(g.path))
	for _, child := range g.children {
		src.WriteString(",\n")
		writeGroup(src, child)
	}
	src.WriteString(")")
}

func writeMethods(src *bytes.Buffer, g *group) {
	fmt.Fprintf(src, "var %s = []resource.Method{\n", variable(g.path))
	for _, m := range g.methods {
		writeMethod(src, m)
	}
	src.WriteString("}\n\n")
	for _, child := range g.children {
		writeMethods(src, child)
	}
}

func writeMethod(src *bytes.Buffer, m resource.Method) {
	src.WriteString("{\n")
	field(src, "Name", strconv.Quote(m.Name))
	field(src, "Use", strconv.Quote(m.Use))
	field(src, "Short", strconv.Quote(m.Short))
	field(src, "Long", strconv.Quote(m.Long))
	field(src, "HTTPMethod", strconv.Quote(m.HTTPMethod))
	field(src, "Path", strconv.Quote(m.Path))
	if len(m.PathParams) > 0 {
		field(src, "PathParams", stringSlice(m.PathParams))
	}
	boolField(src, "OrganizationScoped", m.OrganizationScoped)
	boolField(src, "Public", m.Public)
	boolField(src, "RetrySafe", m.RetrySafe)
	boolField(src, "IdempotencyKeyRequired", m.IdempotencyKeyRequired)
	switch m.IfMatch {
	case resource.Optional:
		field(src, "IfMatch", "resource.Optional")
	case resource.Required:
		field(src, "IfMatch", "resource.Required")
	}
	if len(m.Query) > 0 {
		field(src, "Query", flags(m.Query))
	}
	if b := m.Body; b != nil {
		src.WriteString("Body: &resource.Body{\n")
		field(src, "ContentType", strconv.Quote(b.ContentType))
		if len(b.Fields) > 0 {
			field(src, "Fields", flags(b.Fields))
		}
		if len(b.Fixed) > 0 {
			fixed := []string{}
			for _, f := range b.Fixed {
				fixed = append(fixed, fmt.Sprintf("{Path: %s, JSON: %q}", stringSlice(f.Path), f.JSON))
			}
			field(src, "Fixed", "[]resource.Fixed{"+strings.Join(fixed, ", ")+"}")
		}
		if len(b.FileParts) > 0 {
			parts := []string{}
			for _, part := range b.FileParts {
				parts = append(parts, fmt.Sprintf("{Name: %q, ContentType: %q}", part.Name, part.ContentType))
			}
			field(src, "FileParts", "[]resource.FilePart{"+strings.Join(parts, ", ")+"}")
		}
		src.WriteString("},\n")
	}
	boolField(src, "BinaryResponse", m.BinaryResponse)
	if m.Accept != "" {
		field(src, "Accept", strconv.Quote(m.Accept))
	}
	if p := m.Pagination; p != nil {
		if p.ItemID != "" {
			field(src, "Pagination", fmt.Sprintf("&resource.Pagination{Param: %q, ItemID: %q}", p.Param, p.ItemID))
		} else {
			field(src, "Pagination", fmt.Sprintf("&resource.Pagination{Param: %q}", p.Param))
		}
	}
	boolField(src, "ReturnsOperation", m.ReturnsOperation)
	boolField(src, "Export", m.Export)
	if m.Preview != "" {
		field(src, "Preview", strconv.Quote(m.Preview))
	}
	src.WriteString("},\n")
}

func flags(list []resource.Flag) string {
	var out strings.Builder
	out.WriteString("[]resource.Flag{\n")
	for _, f := range list {
		fmt.Fprintf(&out, "{Name: %q, Path: %s, Type: resource.%s, Usage: %q", f.Name, stringSlice(f.Path), flagType(f.Type), f.Usage)
		if len(f.Values) > 0 {
			fmt.Fprintf(&out, ", Values: %s", stringSlice(f.Values))
		}
		if f.Required {
			out.WriteString(", Required: true")
		}
		out.WriteString("},\n")
	}
	out.WriteString("}")
	return out.String()
}

func flagType(t resource.FlagType) string {
	return map[resource.FlagType]string{
		resource.String:     "String",
		resource.Int:        "Int",
		resource.Number:     "Number",
		resource.Bool:       "Bool",
		resource.StringList: "StringList",
	}[t]
}

func field(src *bytes.Buffer, name, value string) {
	fmt.Fprintf(src, "%s: %s,\n", name, value)
}

func boolField(src *bytes.Buffer, name string, value bool) {
	if value {
		field(src, name, "true")
	}
}

func stringSlice(values []string) string {
	quoted := []string{}
	for _, v := range values {
		quoted = append(quoted, strconv.Quote(v))
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

// variable names a resource's method list: partners.organizations is
// partnersOrganizationsMethods.
func variable(path []string) string {
	name := path[0]
	for _, part := range path[1:] {
		name += strings.ToUpper(part[:1]) + part[1:]
	}
	return name + "Methods"
}

func snake(name string) string {
	return strings.ReplaceAll(Kebab(name), "-", "_")
}

func gofmt(name string, src []byte) ([]byte, error) {
	formatted, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("formatting %s: %w", name, err)
	}
	return formatted, nil
}
